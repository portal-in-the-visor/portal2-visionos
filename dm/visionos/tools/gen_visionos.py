#!/usr/bin/env python3
"""Generate a native visionOS Xcode project for Portal 2 next to the prepared iOS project (<build dir>/xcode).
Usage: python3 dm/visionos/tools/gen_visionos.py <build dir>   (the <id>_build folder that build_ipa_from_nsp.py --platform ios --prepare-xcode made)
Needs xcodegen (brew install xcodegen). The signing team is taken from the prepared iOS project; set your own in Xcode if it is empty.
It reuses the iOS project's generated inputs (Gen/: host sources, embedded game code, rewriter tables, resources.env, xcconfig) and nxnative's
dm/ios/Sources, so the iOS template stays untouched. Output: <build dir>/xcode-visionos/DmVision.xcodeproj (scheme "Portal 2 visionOS")."""
import pathlib, re, subprocess, sys
if len(sys.argv) != 2: sys.exit(__doc__)
NX = pathlib.Path(__file__).resolve().parents[3]   # the nxnative checkout this script lives in
B = pathlib.Path(sys.argv[1]).resolve()
IOS = B / 'xcode'
OUT = B / 'xcode-visionos'
OUT.mkdir(exist_ok=True)
gen = OUT / 'Gen'
if not gen.exists(): gen.symlink_to(IOS / 'Gen')
team = (re.findall(r'DEVELOPMENT_TEAM = ([A-Z0-9]+);', (IOS / 'DmIOS.xcodeproj/project.pbxproj').read_text()) or [''])[0]
extra = NX / 'dm/visionos/Sources'   # visionOS-only sources (immersive space), when present
yml = f'''# Generated by dm/visionos/tools/gen_visionos.py; edit that script, not this file.
name: DmVision
options:
  deploymentTarget:
    visionOS: "26.0"
configFiles:
  Release: Gen/dm.xcconfig
  Debug: Gen/dm.xcconfig
targets:
  DmVision:
    type: application
    platform: visionOS
    sources:
      - path: {NX}/dm/ios/Sources
        excludes: [Info.plist, main.m]
      - path: {NX}/dm/ios/Sources/main.m
        compilerFlags: "-Dmain=dm_ios_uikit_main"   # the SwiftUI app (dm/visionos/Sources) is the entry point; main.m's boot runs through dm_vision_boot
''' + (f'''      - path: {extra}
''' if extra.is_dir() else '') + f'''      - path: Gen/embed.S
      - path: Gen/dm
        type: folder
        buildPhase: resources
      - path: Gen/src
      - path: Gen/main/main.c
        compilerFlags: "-Dmain=dm_main"
    postBuildScripts:
      - name: Copy game resources
        script: PLATFORM_NAME=iphoneos /bin/bash "{NX}/dm/ios/tools/stage_resources.sh"
        basedOnDependencyAnalysis: false
    info:
      path: VisionInfo.plist
      properties:
        CFBundleDisplayName: Portal 2
        CFBundleVersion: "1.0.0"
        CFBundleShortVersionString: "1.0.0"
        UIFileSharingEnabled: true
        NSHandsTrackingUsageDescription: Your right hand aims the portal gun in VR.
        NSWorldSensingUsageDescription: Tracks your head for the VR view.
        LSSupportsOpeningDocumentsInPlace: true
        UIStatusBarHidden: true
        LSApplicationCategoryType: public.app-category.games
        DMShowFPS: "YES"
        DMLanguage: en-US
        LSSupportsGameMode: true
        GCSupportsControllerUserInteraction: true
        GCSupportedGameControllers:
          - ProfileName: ExtendedGamepad
        UIApplicationSceneManifest:
          UIApplicationSupportsMultipleScenes: true
          UIApplicationPreferredDefaultSceneSessionRole: UIWindowSceneSessionRoleApplication
          UISceneConfigurations: {{}}
    settings:
      PRODUCT_BUNDLE_IDENTIFIER: org.nxnative.0100abd01785c000   # same ID as the iPad build: installing over it keeps Documents (romfs.img, saves)
      PRODUCT_NAME: DmVision
      DEVELOPMENT_TEAM: "{team}"
      CODE_SIGN_STYLE: Automatic
      ENABLE_USER_SCRIPT_SANDBOXING: NO
      DM_COPY_GAME_RESOURCES: YES
      ASSETCATALOG_COMPILER_APPICON_NAME: ""
      TARGETED_DEVICE_FAMILY: "7"
      ARCHS: arm64                 # the host is arm64-only (LSE atomics, embedded arm64 game code)
      SUPPORTED_PLATFORMS: xros    # a physical Vision Pro only: the game code cannot run in the Simulator
      SUPPORTS_MACCATALYST: NO
      GCC_C_LANGUAGE_STANDARD: gnu11
      OTHER_CFLAGS: $(inherited) -mcpu=apple-m2
      CLANG_ENABLE_OBJC_ARC: YES
      SWIFT_VERSION: "5.0"
      SWIFT_OBJC_BRIDGING_HEADER: "{extra}/PortalVision-Bridging-Header.h"
      DEBUG_INFORMATION_FORMAT: dwarf
      GCC_WARN_INHIBIT_ALL_WARNINGS: YES
      SYMROOT: {B}/xcode-visionos-derived/Build/Products
      OBJROOT: {B}/xcode-visionos-derived/Build/Intermediates.noindex
schemes:
  Portal 2 visionOS:
    build:
      targets:
        DmVision: all
    run:
      config: Release
      enableGPUValidationMode: disabled
    archive:
      config: Release
'''
(OUT / 'project.yml').write_text(yml)
subprocess.run(['xcodegen', 'generate', '--spec', str(OUT / 'project.yml'), '--project', str(OUT)], check=True)
print('generated', OUT / 'DmVision.xcodeproj', 'team', team or '(none)')
